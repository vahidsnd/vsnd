let current: Dict = fa;

export function setLang(l: 'fa' | 'en') {
  current = l === 'fa' ? fa : en;
  document.documentElement.lang = l;
  document.documentElement.dir = l === 'fa' ? 'rtl' : 'ltr';
}

export function t(key: string): string {
  return current[key] ?? en[key] ?? key;
}

export function isFa() { return current === fa; }

const faDigits = '۰۱۲۳۴۵۶۷۸۹';
export function num(n: number): string {
  const s = Math.round(n).toLocaleString('en-US');
  return isFa() ? s.replace(/\d/g, (d) => faDigits[+d]).replace(/,/g, '٬') : s;
}

/** pick the localised field of a catalog entry */
export function loc<T extends { name: string; nameFa: string }>(o: T): string {
  return isFa() ? o.nameFa : o.name;
}

export function duration(ms: number): string {
  const s = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), sec = s % 60;
  const pad = (x: number) => String(x).padStart(2, '0');
  if (h >= 48) {
    const d = Math.floor(h / 24);
    const txt = isFa() ? `${d} روز ${h % 24} ساعت` : `${d}d ${h % 24}h`;
    return isFa() ? txt.replace(/\d/g, (x) => faDigits[+x]) : txt;
  }
  const out = h > 0 ? `${h}:${pad(m)}:${pad(sec)}` : `${m}:${pad(sec)}`;
  return isFa() ? out.replace(/\d/g, (d) => faDigits[+d]) : out;
}
